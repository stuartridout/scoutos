// The ScoutOS compass mark alone — for watermarks and icons (masterbrand §3).
// Monochrome currentColor by default; decorative alongside text, so aria-hidden.
export function Compass({
  size = 24,
  color = 'currentColor',
  style,
}: {
  size?: number | string;
  color?: string;
  style?: CSSProperties;
}) {
  return (
    <svg viewBox="2360 945 694 694" width={size} height={size} role="img" aria-hidden="true" focusable="false" style={style}>
      <path fillRule="evenodd" d={COMPASS_PATH} fill={color} />
    </svg>
  );
}

// The ScoutOS wordmark. `product` appends the product name in Cal Sans Bold at
// the mark's cap height. tone "two-tone" is the family's dark-surface treatment
// (masterbrand §4.3): ScoutOS segment in ScoutOS yellow, product name in paper.
export function Wordmark({
  product,
  size = 20,
  tone = 'mono',
  style,
}: {
  product?: string;
  size?: number;
  tone?: 'mono' | 'two-tone';
  style?: CSSProperties;
}) {
  const markColor = tone === 'two-tone' ? tokens.yellow : 'currentColor';
  const productColor = tone === 'two-tone' ? tokens.paper : 'currentColor';
  const label = product ? `ScoutOS ${product}` : 'ScoutOS';

  return (
    <span
      aria-label={label}
      style={{
        display: 'inline-block',
        fontFamily: fonts.display,
        fontSize: size,
        lineHeight: 1,
        whiteSpace: 'nowrap',
        ...style,
      }}
    >
      <svg
        viewBox={SCOUTOS_VIEWBOX}
        height="1em"
        width={`${SCOUTOS_RATIO}em`}
        role="img"
        aria-hidden={product ? true : undefined}
        aria-label={product ? undefined : 'ScoutOS'}
        style={{ verticalAlign: `${-BASELINE_DROP}em`, flex: 'none' }}
      >
        <path d={SCOUT_PATH} fill={markColor} />
        <path fillRule="evenodd" d={COMPASS_PATH} fill={markColor} />
        <path d={LIGHT_S_PATH} fill={markColor} />
      </svg>
      {product ? (
        <span
          aria-hidden="true"
          style={{
            marginLeft: '0.26em',
            fontWeight: 700,
            // Sized so the product name's cap height matches the outlined
            // mark's caps (≈0.884em of the mark's box height).
            fontSize: '1.2em',
            letterSpacing: '-0.012em',
            color: productColor,
          }}
        >
          {product}
        </span>
      ) : null}
    </span>
  );
}
